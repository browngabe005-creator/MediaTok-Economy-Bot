function slug(s) {return s.normalize('NFKD').replace(/[^a-zA-Z0-9 ]/g,'').trim().toLowerCase().replace(/\s+/g,'-');}
export const CATALOG = raw.map(([type,series,name,rarity]) => ({id: `${type}:${slug(series)}:${slug(name)}`,type,series,name,rarity,value:RARITIES[rarity].value}));
export const BY_ID = new Map(CATALOG.map(c => [c.id,c]));
export function findCharacter(query) {
  const q = String(query).trim().toLowerCase();
  return CATALOG.find(c => c.id === q)
    ?? CATALOG.find(c => `${c.name} — ${c.series}`.toLowerCase() === q)
    ?? CATALOG.find(c => c.name.toLowerCase() === q)
    ?? null;
}
export function characterOptions(query, excluded = new Set()) {
 const q = String(query ?? '').trim().toLowerCase();
 return CATALOG.filter(c => !excluded.has(c.id) && (`${c.name} ${c.series} ${c.type}`.toLowerCase().includes(q)))
    .slice(0,25).map(c=>({ name:`${c.name} (${c.series})`.slice(0,100),value:c.id }));
}
